import { Router } from "express";

import {
  createProduct,
  getProducts,
  getProductById,
  updateProduct,
  updateProductStock,
  updateProductStatus,
  deleteProduct,
} from "../controllers/product.controller";


const router = Router();

/*
|--------------------------------------------------------------------------
| CREATE PRODUCT
|--------------------------------------------------------------------------
| POST /api/products
|--------------------------------------------------------------------------
*/

router.post(
  "/",
 
  createProduct
);

/*
|--------------------------------------------------------------------------
| GET ALL PRODUCTS
|--------------------------------------------------------------------------
| GET /api/products
| GET /api/products?keyword=milk
|--------------------------------------------------------------------------
*/

router.get(
  "/",
 
  getProducts
);

/*
|--------------------------------------------------------------------------
| GET PRODUCT BY ID
|--------------------------------------------------------------------------
| GET /api/products/:id
|--------------------------------------------------------------------------
*/

router.get(
  "/:id",
  
  getProductById
);

/*
|--------------------------------------------------------------------------
| UPDATE PRODUCT
|--------------------------------------------------------------------------
| PUT /api/products/:id
|--------------------------------------------------------------------------
*/

router.put(
  "/:id",
 
  updateProduct
);

/*
|--------------------------------------------------------------------------
| UPDATE STOCK
|--------------------------------------------------------------------------
| PATCH /api/products/:id
|--------------------------------------------------------------------------
*/

router.patch(
  "/:id",

  updateProductStock
);

/*
|--------------------------------------------------------------------------
| UPDATE STATUS
|--------------------------------------------------------------------------
| PATCH /api/products/:id/status
|--------------------------------------------------------------------------
*/

router.patch(
  "/:id/status",
 
  updateProductStatus
);

/*
|--------------------------------------------------------------------------
| DELETE PRODUCT
|--------------------------------------------------------------------------
| DELETE /api/products/:id
|--------------------------------------------------------------------------
*/

router.delete(
  "/:id",
  
  deleteProduct
);

export default router;